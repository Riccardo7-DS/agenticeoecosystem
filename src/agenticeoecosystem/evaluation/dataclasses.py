"""
dataclasses.py — Pydantic schemas for tasks, solutions, and result tracking.

These mirror the GeoBenchX dataclasses but are domain-agnostic.
Adapt Step/Solution to whatever output your pipeline produces.
"""

import json
import os
from collections import Counter
from typing import Any, Dict, List, Optional, Union

import numpy as np
from pydantic import BaseModel, Field

from .constants import NO_LABEL, ScoreValues, TaskLabels
from agenticeoecosystem.definitions import GEOBENCH_RESULTS, TASKS_FOLDER

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _generate_task_id() -> str:
    """Creates a unique ID string like TASK_260408_143022_123456."""
    import random
    from datetime import datetime
    ts = datetime.now().strftime("%y%m%d_%H%M%S")
    rand = random.randint(100000, 999999)
    return f"TASK_{ts}_{rand}"


# ---------------------------------------------------------------------------
# Step & Solution — adapt to your pipeline's output format
# ---------------------------------------------------------------------------

class Step(BaseModel):
    """
    One atomic action taken by the agent.
    Replace / extend fields to match what your pipeline records.
    """
    function_name: str                      # e.g. tool name or action type
    arguments: Dict[str, Any] = Field(default_factory=dict)
    comment: Optional[str] = None          # Optional hint used during grading

    class Config:
        extra = "forbid"


class Solution(BaseModel):
    """Ordered sequence of steps produced by an agent run."""
    steps: List[Step] = Field(default_factory=list)

    def __len__(self):
        return len(self.steps)

    def __str__(self):
        lines = []
        for i, s in enumerate(self.steps, 1):
            args = ", ".join(f"{k}={v!r}" for k, v in s.arguments.items())
            line = f"{i}. {s.function_name}({args})"
            if s.comment:
                line += f"  # {s.comment}"
            lines.append(line)
        return "\n".join(lines)

    __repr__ = __str__


# ---------------------------------------------------------------------------
# Task
# ---------------------------------------------------------------------------

class Task(BaseModel):
    """
    Single benchmark task with reference solution(s) and evaluation results.

    Fill in generated_solution after running your pipeline, then
    match_score_LLM after the LLM evaluator runs, and match_score_Human
    after manual review.
    """
    task_ID: str = Field(default_factory=_generate_task_id)
    task_text: str

    # Categorisation — use TaskLabels enum or plain strings
    task_labels: Optional[List[TaskLabels]] = Field(default_factory=list)

    # Reference / ground-truth
    reference_solution_description: Optional[str] = None
    reference_solutions: Optional[List[Solution]] = Field(default_factory=list)

    # Generated by your pipeline
    generated_solution: Optional[Solution] = None
    generated_solution_input_tokens: Optional[int] = None
    generated_solution_output_tokens: Optional[int] = None

    # LLM-as-judge evaluation (single evaluator, kept for backward compat)
    match_reasoning_LLM: Optional[str] = None
    match_score_LLM: Optional[ScoreValues] = None

    # Multi-evaluator scores — keyed by evaluator label
    evaluator_scores: Dict[str, Optional[int]] = Field(default_factory=dict)
    evaluator_reasoning: Dict[str, Optional[str]] = Field(default_factory=dict)

    # Human evaluation
    match_reasoning_Human: Optional[str] = None
    match_score_Human: Optional[ScoreValues] = None

    class Config:
        extra = "forbid"

    def __str__(self):
        lines = [
            f"ID    : {self.task_ID}",
            f"Text  : {self.task_text}",
            f"Labels: {[l.value for l in self.task_labels]}",
            f"Score (LLM)  : {self.match_score_LLM}",
            f"Score (Human): {self.match_score_Human}",
        ]
        return "\n".join(lines)

    __repr__ = __str__


# ---------------------------------------------------------------------------
# TaskSet
# ---------------------------------------------------------------------------

class TaskSet(BaseModel):
    """
    Collection of Tasks with optional metadata (e.g. model name, temperature).
    Supports iteration, indexing, stratified sampling, and file I/O.
    """
    metadata: Dict[str, Any] = Field(default_factory=dict)
    tasks: List[Task] = Field(default_factory=list)

    # -- Collection interface -------------------------------------------------

    def __iter__(self):
        return iter(self.tasks)

    def __len__(self):
        return len(self.tasks)

    def __getitem__(self, index: Union[int, slice]) -> Union[Task, List[Task]]:
        return self.tasks[index]

    def __setitem__(self, index: Union[int, slice], value: Union[Task, List[Task]]) -> None:
        self.tasks[index] = value

    def append(self, task: Task) -> None:
        self.tasks.append(task)

    def extend(self, tasks: List[Task]) -> None:
        self.tasks.extend(tasks)

    # -- I/O ------------------------------------------------------------------

    @classmethod
    def read_from_file(cls, filename: str, folder: str = TASKS_FOLDER) -> "TaskSet":
        """Load a TaskSet from a JSON file."""
        file_path = os.path.join(folder, filename)
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        return cls(**data)

    def save_to_file(self, filename: str, folder: str = GEOBENCH_RESULTS) -> None:
        """Save the TaskSet to a JSON file (creates the folder if needed)."""
        os.makedirs(folder, exist_ok=True)
        file_path = os.path.join(folder, filename)
        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(self.model_dump(), f, indent=4, ensure_ascii=False)

    # -- Analytics ------------------------------------------------------------

    def get_label_counts(self) -> Dict[str, int]:
        counter: Counter = Counter()
        for task in self.tasks:
            if not task.task_labels:
                counter.update([NO_LABEL])
            else:
                counter.update(task.task_labels)
        return dict(counter)

    def sample_stratified(self, num_samples: int) -> "TaskSet":
        """
        Return a new TaskSet with `num_samples` tasks, weighted so that
        under-represented labels are over-sampled (inverse-frequency weighting).
        """
        if num_samples >= len(self.tasks):
            return TaskSet(metadata=self.metadata, tasks=list(self.tasks))

        label_freq = self.get_label_counts()
        weights = []
        for t in self.tasks:
            if t.task_labels:
                w = sum(1.0 / label_freq[l] for l in t.task_labels if l in label_freq)
            else:
                w = 1.0 / label_freq[NO_LABEL]
            weights.append(w)

        probs = np.array(weights, dtype=float)
        probs /= probs.sum()
        indices = np.random.choice(len(self.tasks), size=num_samples, replace=False, p=probs)
        return TaskSet(metadata=self.metadata, tasks=[self.tasks[i] for i in indices])

    def select_by_labels(self, labels: List[str]) -> "TaskSet":
        """Filter to tasks that share at least one label with `labels`."""
        label_set = set(labels)
        if not labels:
            filtered = [t for t in self.tasks if not t.task_labels]
        else:
            filtered = [t for t in self.tasks if any(l in label_set for l in t.task_labels)]
        return TaskSet(metadata=self.metadata, tasks=filtered)

    def select_by_ids(self, task_ids: List[str]) -> "TaskSet":
        """Return a TaskSet containing only the tasks whose task_ID is in `task_ids`."""
        id_set = set(task_ids)
        filtered = [t for t in self.tasks if t.task_ID in id_set]
        return TaskSet(metadata=self.metadata, tasks=filtered)

    def subset(
        self,
        label: Union[str, "TaskLabels"],
        n: Optional[int] = None,
    ) -> "TaskSet":
        """
        Return a TaskSet filtered to a single category, optionally capped at n tasks.

        Args:
            label : A TaskLabels enum value or its string value (e.g. "Tool Grounding").
            n     : Maximum number of tasks to return.  None means no limit.

        Example:
            smoke = tasks.subset(TaskLabels.TOOL_GROUNDING, n=2)
            smoke = tasks.subset("Tool Grounding", n=3)
        """
        label_str = label.value if isinstance(label, TaskLabels) else label
        filtered = [
            t for t in self.tasks
            if any(
                (l.value if isinstance(l, TaskLabels) else l) == label_str
                for l in (t.task_labels or [])
            )
        ]
        if n is not None:
            filtered = filtered[:n]
        return TaskSet(metadata=self.metadata, tasks=filtered)

    def score_summary_for_evaluator(self, evaluator_label: str) -> Dict[str, Any]:
        """Accuracy stats for a specific evaluator stored in evaluator_scores."""
        scores = [
            t.evaluator_scores.get(evaluator_label)
            for t in self.tasks
            if t.evaluator_scores.get(evaluator_label) is not None
        ]
        if not scores:
            return {"n": 0}
        return {
            "n": len(scores),
            "match": sum(1 for s in scores if s == ScoreValues.MATCH),
            "partial": sum(1 for s in scores if s == ScoreValues.PARTIAL_MATCH),
            "no_match": sum(1 for s in scores if s == ScoreValues.NO_MATCH),
            "accuracy_full": sum(1 for s in scores if s == ScoreValues.MATCH) / len(scores),
            "accuracy_partial_or_full": sum(
                1 for s in scores if s >= ScoreValues.PARTIAL_MATCH
            ) / len(scores),
        }

    def score_summary(self) -> Dict[str, Any]:
        """
        Compute basic accuracy stats from LLM and Human scores.
        Returns counts and accuracy for each scorer.
        """
        summary: Dict[str, Any] = {}
        for scorer in ("LLM", "Human"):
            scores = [
                getattr(t, f"match_score_{scorer}")
                for t in self.tasks
                if getattr(t, f"match_score_{scorer}") is not None
            ]
            if not scores:
                summary[scorer] = {"n": 0}
                continue
            summary[scorer] = {
                "n": len(scores),
                "match": scores.count(ScoreValues.MATCH),
                "partial": scores.count(ScoreValues.PARTIAL_MATCH),
                "no_match": scores.count(ScoreValues.NO_MATCH),
                "accuracy_full": scores.count(ScoreValues.MATCH) / len(scores),
                "accuracy_partial_or_full": sum(
                    1 for s in scores if s >= ScoreValues.PARTIAL_MATCH
                ) / len(scores),
            }
        return summary
